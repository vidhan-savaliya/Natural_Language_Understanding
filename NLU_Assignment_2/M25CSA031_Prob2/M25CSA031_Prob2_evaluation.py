"""
Problem 2 : Quantitative Evaluation

computing a novalty rate and diversity for each models generated names.


Metrics:
    Novelty Rate = (names NOT in training set) / ( total generated ) * 100%
    Diversity    = (unique generated names) / ( total generated ) * 100%

Novalty rate is the percentage of new names generated by the model that are not present in the training set.
Diversity is the percentage of unique names generated by the model.



"""

import os


def load_names(filepath):
    """Read names from a text file."""
    if not os.path.exists(filepath):
        print(f"WARNING: {filepath} not found! Run the model script first.")
        return []
    with open(filepath, "r", encoding="utf-8") as f:
        return [line.strip() for line in f if line.strip()]


def compute_novelty(generated_names, training_set):
    """
    fraction of generated names not in the training set
    for higher novelty a model is more creative, not momorized.

   
    """
    if not generated_names:
        return 0.0
    novel = [name for name in generated_names if name not in training_set]
    return len(novel) / len(generated_names) * 100


def compute_diversity(generated_names):
    """
    Fraction of the generated names which are unique.
    for higher diversity a model is more creative, not repeating itself.
    
    """
    if not generated_names:
        return 0.0
    unique = set(generated_names)
    return len(unique) / len(generated_names) * 100


if __name__ == "__main__":
    # Load the training data for comparison
    training_names = load_names("TrainingNames.txt")
    training_set = set(training_names)
    print(f"Training set: {len(training_names)} names ({len(training_set)} unique)\n")

    # Map each model to its generated output file
    model_outputs = {
        "Vanilla RNN":     "generated_vanilla_rnn.txt",
        "BLSTM":           "generated_blstm.txt",
        "RNN + Attention": "generated_rnn_attention.txt",
    }

    print("=" * 60)
    print("  TASK 2: QUANTITATIVE EVALUATION")
    print("=" * 60)

    results = {}

    for model_name, filepath in model_outputs.items():
        generated = load_names(filepath)
        if not generated:
            continue

        novelty = compute_novelty(generated, training_set)
        diversity = compute_diversity(generated)

        results[model_name] = {
            "total": len(generated),
            "unique": len(set(generated)),
            "novelty": novelty,
            "diversity": diversity,
        }

        print(f"\n {model_name} ")
        print(f"  Total generated: {len(generated)}")
        print(f"  Unique names:    {len(set(generated))}")
        print(f"  Novelty Rate:    {novelty:.1f}%")
        print(f"  Diversity:       {diversity:.1f}%")

    # Comparison table
    if results:
        print("\n" + "=" * 60)
        print("  COMPARISON TABLE")
        print("=" * 60)
        print(f"  {'Model':<20} {'Novelty':<15} {'Diversity':<15}")
        print(f"  {'-'*50}")
        for model_name, r in results.items():
            print(f"  {model_name:<20} {r['novelty']:.1f}%{'':<10} {r['diversity']:.1f}%")
